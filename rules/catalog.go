package rules

import (
	"fmt"
	"strings"
)

// Catalog renders the built-in rules as the Markdown of rules/README.md.
// It is generated (see TestCatalogUpToDate), not written by hand.
func Catalog(rs []Rule) string {
	var b strings.Builder
	b.WriteString("# Rules\n\n")
	b.WriteString("<!-- Generated by PROSA_RULES_CATALOG=1 go test ./rules/ -run TestCatalogUpToDate. Do not edit. -->\n\n")
	b.WriteString("A rule is a best practice written in prose. The planner reads the rules that apply to the resource types of a plan, and a reviewer checks the plan against them before you see it.\n\n")
	b.WriteString("- Disable a rule for the project: list its ID in `rules/disabled.txt`, or pass `--disable-rule ID` for one run.\n")
	b.WriteString("- Make an exception: name the rule ID in the prose of the intent, with the reason.\n")
	b.WriteString("- Add your own: write a Markdown file under `rules/` with the same front matter (`id`, `title`, `applies_to`, `source`) and the rule as prose. Give it your own ID prefix (e.g. `ACME-NET-001`), never the provider's (`AWS-`), so that a future Prosa release cannot collide with it.\n\n")
	b.WriteString("## AWS\n")
	for _, r := range rs {
		fmt.Fprintf(&b, "\n### %s — %s\n\n", r.ID, r.Title)
		fmt.Fprintf(&b, "Applies to: `%s`\n\n", strings.Join(r.AppliesTo, "`, `"))
		b.WriteString(r.Body + "\n")
		if len(r.Sources) > 0 {
			b.WriteString("\nSource:\n")
			for _, s := range r.Sources {
				fmt.Fprintf(&b, "- [%s](%s)\n", s.Label, s.URL)
			}
		}
	}
	return b.String()
}
